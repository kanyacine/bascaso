const BY_CODE: ReadonlyMap<string, StorefrontMarket> = new Map(
  STOREFRONT_MARKETS.map((c) => [c.code, c]),
);

/** The floor used for a storefront the table does not know. */
export const SMALLEST_MARKET = Math.min(...STOREFRONT_MARKETS.map((c) => c.market));

/** Market size relative to the US (us = 1). Unknown codes get the smallest market. */
export function marketSize(country: string | null | undefined): number {
  if (!country) return 1;
  return BY_CODE.get(country.toLowerCase())?.market ?? SMALLEST_MARKET;
}
